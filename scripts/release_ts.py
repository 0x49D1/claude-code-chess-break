"""Writes hooks/release.ts from .claude-plugin/plugin.json and CHANGELOG.md.

The mod reads no file of its own at run time (in some installs it can't), so its version, home
page and changes are built in. Run it after a version bump and its CHANGELOG.md lines:

    python3 scripts/release_ts.py

The release workflow checks that the file is up to date.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def releases(text):
    """CHANGELOG.md's versions, newest first: `## 0.5.0 (2026-11-10)` and its `- ` lines, plain."""
    found = []
    for line in text.splitlines():
        heading = re.match(r"^## (\S+)(?: \((.+)\))?\s*$", line)
        if heading:
            found.append({"version": heading.group(1), "date": heading.group(2), "changes": []})
        elif line.startswith("- ") and found:
            found[-1]["changes"].append(re.sub(r"\*\*|`", "", line[2:]))
    return found


def main():
    with open(os.path.join(ROOT, ".claude-plugin", "plugin.json"), encoding="utf-8") as f:
        manifest = json.load(f)
    with open(os.path.join(ROOT, "CHANGELOG.md"), encoding="utf-8") as f:
        changes = releases(f.read())
    if not changes or changes[0]["version"] != manifest["version"]:
        raise SystemExit(f"CHANGELOG.md's newest version is not plugin.json's {manifest['version']}")
    lines = [
        "// Generated by scripts/release_ts.py from .claude-plugin/plugin.json and CHANGELOG.md. Do not edit by hand.",
        "import type { Release } from '../types'",
        "",
        f"export const VERSION = {json.dumps(manifest['version'])}",
        f"export const HOMEPAGE = {json.dumps(manifest['homepage'])}",
        "",
        "/** CHANGELOG.md's versions, newest first. */",
        "export const RELEASES: Release[] = [",
    ]
    for r in changes:
        date = f", date: {json.dumps(r['date'], ensure_ascii=False)}" if r["date"] else ""
        items = ", ".join(json.dumps(c, ensure_ascii=False) for c in r["changes"])
        lines.append(f"  {{ version: {json.dumps(r['version'])}{date}, changes: [{items}] }},")
    lines.append("]")
    with open(os.path.join(ROOT, "hooks", "release.ts"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
