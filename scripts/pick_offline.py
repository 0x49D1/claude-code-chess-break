"""Picks the offline puzzle set from the Lichess puzzle database (CC0), read as CSV on stdin.

    curl -s https://database.lichess.org/lichess_db_puzzle.csv.zst | zstd -dc | python3 scripts/pick_offline.py

Keeps popular, much-played puzzles: for each training theme, a few in each rating band, and
writes hooks/offline/puzzles.ts. Stops reading once every theme has its share.
"""
import csv
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEMES_TS = os.path.join(ROOT, 'hooks', 'training', 'themes.ts')
OUT = os.path.join(ROOT, 'hooks', 'offline', 'puzzles.ts')

BANDS = [(600, 1000), (1000, 1300), (1300, 1600), (1600, 1900), (1900, 2200), (2200, 2600)]
PER_BAND = 7
MIN_POPULARITY = 85
MIN_PLAYS = 500


def training_themes():
    source = open(THEMES_TS, encoding='utf-8').read()
    groups = source[source.index('THEME_GROUPS'):source.index('}', source.index('THEME_GROUPS'))]
    return re.findall(r"'([A-Za-z0-9]+)'", groups)


def main():
    themes = training_themes()
    need = {(t, b): PER_BAND for t in themes for b in range(len(BANDS))}
    picked = {}
    for row in csv.DictReader(sys.stdin):
        if not need:
            break
        if int(row['Popularity']) < MIN_POPULARITY or int(row['NbPlays']) < MIN_PLAYS:
            continue
        rating = int(row['Rating'])
        band = next((i for i, (lo, hi) in enumerate(BANDS) if lo <= rating < hi), None)
        if band is None:
            continue
        tags = row['Themes'].split()
        wanted = [t for t in tags if need.get((t, band))]
        if not wanted:
            continue
        for t in wanted:
            need[(t, band)] -= 1
            if not need[(t, band)]:
                del need[(t, band)]
        picked[row['PuzzleId']] = [row['PuzzleId'], row['FEN'], row['Moves'], rating, row['Themes']]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by scripts/pick_offline.py from the Lichess puzzle database (CC0,\n')
        f.write('// https://database.lichess.org/#puzzles). Do not edit by hand.\n')
        f.write('// Each row: id, FEN before the opponent\'s move, moves (UCI, the opponent\'s first), rating, themes.\n\n')
        f.write('export const PUZZLES: [string, string, string, number, string][] = [\n')
        for p in picked.values():
            f.write('  ' + json.dumps(p, ensure_ascii=False) + ',\n')
        f.write(']\n')
    short = sorted({t for t, _ in need})
    print(f'{len(picked)} puzzles written; themes short of a full share: {", ".join(short) or "none"}', file=sys.stderr)


if __name__ == '__main__':
    main()
